        def self.move(from_row, from_col, faction_sym)
          entry = MOVEMENTS["#{from_row},#{from_col}"]
          return unless entry

          index = FACTION_INDEX[faction_sym]
          return unless index

          entry[index].split(',').map(&:to_i)
        end

        def self.valid_position?(row, col)
          MOVEMENTS.key?("#{row},#{col}")
        end

        def self.all_positions
          MOVEMENTS.keys.map { |key| key.split(',').map(&:to_i) }
        end

        def self.polarization_level(row, col)
          POSITION_LEVELS["#{row},#{col}"] || 0
